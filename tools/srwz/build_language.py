"""The language this build produces: corpus language tag and literal readback targets.

Gates compare rebuilt text with fixed Simplified strings (stage 38's title, the ISSUE-020 ticker, ...). A
Traditional build carries config/zh-hant/readback-literals.json, generated by tools/zh_hant/build_dual.py from the
parallel corpora (Simplified string -> its Traditional counterpart); there the same gates compare against the
Traditional string. Without that file every literal is returned unchanged.
The same file marks the build as Traditional for the corpus language checks (corpus_language).
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

LITERALS = Path("config/zh-hant/readback-literals.json")


@lru_cache(maxsize=None)
def _document(project_root: str) -> dict | None:
    path = Path(project_root) / LITERALS
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _literals(project_root: str) -> dict | None:
    document = _document(project_root)
    return None if document is None else document["literals"]


def expected_literal(text, project_root: Path):
    literals = _literals(str(project_root))
    if literals is None or not isinstance(text, str) or not any("㐀" <= c <= "鿿" for c in text):
        return text
    if text not in literals:
        raise ValueError(f"readback literal has no Traditional counterpart: {text!r}")
    return literals[text]


def expected_literals(expectations: dict, project_root: Path) -> dict:
    return {key: expected_literal(value, project_root) for key, value in expectations.items()}


def traditional_build(project_root: Path) -> bool:
    """True in the Traditional build of the dual disc. Its inputs are the parallel of a Simplified build's
    (tools/zh_hant/sync_corpus.py --check), so guards that compare the frozen Simplified baseline with the text
    about to be written (concurrent-edit guards) are decided by that Simplified build."""
    return _literals(str(project_root)) is not None


def corpus_language(project_root: Path) -> str:
    """The "language" tag the translation corpora of this build carry."""
    return "zh-Hant" if _literals(str(project_root)) is not None else "zh-Hans"


def expected_characters(text, project_root: Path):
    """For glyph-presence checks over spliced texts: the literal if known, else character by character."""
    document = _document(str(project_root))
    if document is None or not isinstance(text, str):
        return text
    if text in document["literals"]:
        return document["literals"][text]
    return "".join(document["characters"].get(c, c) for c in text)
