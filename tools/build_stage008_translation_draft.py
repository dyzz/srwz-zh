def main() -> None:
    draft = json.loads(MACHINE_DRAFT.read_text(encoding="utf-8"))
    expected = set(range(len(draft["translations"])))
    if set(DECISIONS) != expected:
        raise SystemExit(
            f"stage 008 decision index mismatch: "
            f"expected={sorted(expected)} actual={sorted(DECISIONS)}"
        )
    protected = (
        "三位一体都市",
        "三位一体能量",
        "圣日耳曼城",
        "格兰骑士团",
        "地球战骑队",
        "格兰凯撒",
        "格兰迪瓦",
        "龙神丸",
        "桑巴德",
        "G幻影机",
        "雷文",
        "泽拉拜亚",
        "木卫一",
        "超级机器人",
    )
    reflowed = []
    layout_errors = []
    for index in range(len(DECISIONS)):
        text = DECISIONS[index]
        try:
            result = reflow_chinese_dialogue(
                text,
                protected_terms=protected,
                line_width=24,
                max_lines=3,
            )
        except ValueError as error:
            layout_errors.append((index, str(error), text))
            reflowed.append(text)
        else:
            reflowed.append(result.text)
    if layout_errors:
        for index, error, text in layout_errors:
            print(f"layout error {index}: {error}: {text}")
        raise SystemExit(1)
    draft["draft_kind"] = "human_reviewed"
    draft["editorial_status"] = "reviewed"
    draft["translation_provider"] = {
        "name": "project editorial review",
        "tool_version": 1,
    }
    draft["translations"] = reflowed
    refs_by_index = draft.get("glossary_refs_by_index", {})
    if isinstance(refs_by_index, dict):
        refs_by_index["25"] = [
            term_id
            for term_id in refs_by_index.get("25", [])
            if term_id != "system/pilot"
        ]
        draft["glossary_refs_by_index"] = refs_by_index
    draft["notes_by_index"] = {
        "33": "场景演出占位，采用术语表中的黑屏。",
        "121": "雪貂叫声，按动物拟声处理。",
        "135": "雪貂叫声，按动物拟声处理。",
        "149": "莉露的含混回应，保留语气。",
        "154": "莉露的惊讶回应，保留语气。",
    }
    draft["glossary_exceptions_by_index"] = {
        "3": ["system/pilot"],
        "6": ["system/pilot"],
        "25": ["system/pilot"],
        "54": ["system/pilot"],
    }
    OUTPUT.write_text(
        json.dumps(draft, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"reviewed stage 008 draft: {OUTPUT}")
    print(f"unique decisions: {len(reflowed)}")


if __name__ == "__main__":
    main()
