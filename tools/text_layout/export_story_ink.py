"""Export rightmost ink per scanline from two prepared Original font components."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
from srwz import latin_bank
from srwz.font import ascii_glyph_index, decode_glyph, decode_vt1_font_segment, glyph_index_for_code, read_extended_glyph_table
from srwz.text import load_text_table, original_fullwidth_ascii_overrides


def load_font_component(project, traditional):
    manifest = json.loads((project / 'manifests/zh-release-font-validation.json').read_bytes())

    def locked(ref):
        raw = (project / ref['path']).read_bytes()
        if hashlib.sha256(raw).hexdigest() != ref['sha256']:
            raise ValueError(f"Font component input drift: {ref['path']}")
        return raw

    source = load_text_table(project / 'vendor/upstream-python/project/tbl_all.json')
    component = manifest['font_component']
    elf = locked(component['slps'])
    font = decode_vt1_font_segment(elf, locked(component['vt1'])).decoded
    extended = read_extended_glyph_table(elf)
    proposal = json.loads(locked(manifest['proposal']))
    primary = {r['character']: int(r['code'], 16) for r in proposal['assignments']}
    aliases = {r['character']: int(r['code'], 16) for r in proposal['surface_alias_assignments']}
    stored = {**primary, **aliases, **original_fullwidth_ascii_overrides(source)}
    owners = {code: char for char, code in stored.items()}
    glyphs = {}
    for ch, code in {**source.inverse_characters, **stored}.items():
        if len(ch) != 1 or owners.get(code, ch) != ch:
            continue
        try:
            glyphs[ch] = (ascii_glyph_index(code) if 32 <= code < 127 else
                          glyph_index_for_code(code, extended, glyph_count=len(font)//288, linear=traditional))
        except ValueError:
            continue
    banks = {c:latin_bank.base_glyph_index()+slot for slot,c in latin_bank.slot_characters().items()}

    return font, glyphs, banks, manifest


def load_component(project, traditional):
    font, glyphs, banks, _ = load_font_component(project, traditional)

    def outlines(mapping):
        result = {}
        for ch, index in mapping.items():
            pixels = decode_glyph(font, index)
            # Cell coordinates are encoded as A=empty, B=first column, ..., Y=last column.
            rows = [max((x+1 for x in range(24) if pixels[24*y+x] >= 3), default=0) for y in range(24)]
            if any(rows):
                result[ch] = ''.join(chr(65+x) for x in rows)
        return result
    return outlines(glyphs), outlines(banks), hashlib.sha256(font).hexdigest()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('simplified_project', type=Path)
    p.add_argument('traditional_project', type=Path)
    p.add_argument('--output', type=Path, default=ROOT/'shared/text-layout/story-ink-data.mjs')
    args = p.parse_args()
    sc, bank, sc_hash = load_component(args.simplified_project, False)
    tc, tc_bank, tc_hash = load_component(args.traditional_project, True)
    if bank != tc_bank:
        raise ValueError('Latin bank differs across the two fonts')
    # Characters present in just one region may occupy the other region's reassigned slots.
    common = {k:v for k,v in sc.items() if tc.get(k)==v}
    data = dict(fonts=[sc_hash,tc_hash], common=common,
                hans={k:v for k,v in sc.items() if k not in common},
                hant={k:v for k,v in tc.items() if k not in common}, bank=bank)
    args.output.write_text('// Generated by tools/text_layout/export_story_ink.py\nexport const storyInkData = '+
                           json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=True)+';\n')

if __name__ == '__main__':
    main()
