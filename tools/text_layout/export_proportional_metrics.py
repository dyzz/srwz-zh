"""Extract candidate metrics from an existing font; never modify the font."""
from pathlib import Path
import argparse, json, sys
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools'))
from srwz.proportional_metrics import build_registry
p=argparse.ArgumentParser();p.add_argument('font',type=Path);p.add_argument('--offset',type=lambda x:int(x,0),default=0);p.add_argument('--check',action='store_true');a=p.parse_args()
with a.font.open('rb') as f:
    f.seek(a.offset);font=f.read(4480*288)
data=build_registry(font)
content='// Generated by tools/text_layout/export_proportional_metrics.py.\nexport const proportionalMetrics = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n'
out=ROOT/'shared/text-layout/proportional-metrics.mjs'
if a.check:
    assert out.read_text()==content,'Proportional metrics stale'
else:
    out.write_text(content)
print(data['fontSha256'])
