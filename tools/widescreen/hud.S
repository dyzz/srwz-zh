# The native UI submits one contiguous GIF stream after the field's world pass.
# Keep world matrices and texture coordinates intact. Map UI vertices and
# horizontal clip intervals to the same centered 4:3 layout.
# Record the native composite draw span, including clipped children and text.
right_menu:
        addiu   $sp,$sp,-16
        sd      $ra,0($sp)
        lui     $v1,%hi(menu_start)
        sw      $a1,%lo(menu_start)($v1)
        jalr    $t9
        nop
        lw      $t0,menu_start
        subu    $t0,$v0,$t0
        lui     $v1,%hi(menu_size)
        sw      $t0,%lo(menu_size)($v1)
        ld      $ra,0($sp)
        jr      $ra
        addiu   $sp,$sp,16
menu_start: .word 0
menu_size: .word 0
hud_submit:
        lw      $t0,map_drawn
        bnez    $t0,hud_field
        nop
        lui     $t0,%hi(menu_size)     # fixed compositions use the centered HUD
        sw      $zero,%lo(menu_size)($t0)
        lw      $t0,wide_enabled
        bnez    $t0,hud_field
        nop
        j       HUD_SUBMIT
        nop
hud_field:
        # First finalize the last REF. Uploads can split a single menu into
        # several REF chunks well before the world has drawn for this field.
        addiu   $sp,$sp,-32
        sw      $zero,16($sp)           # textured scene geometry seen
        li      $t0,128
        sw      $t0,20($sp)             # native full-screen fade multiplier
        sd      $ra,0($sp)
        jal     HUD_SUBMIT
        sd      $a0,8($sp)
        lw      $v0,HUD_CHAIN+8         # first DMA tag
        lw      $v1,HUD_CHAIN           # one past last REF
        li      $t9,HUD_ARENA
hud_chunk:
        beq     $v0,$v1,hud_finish
        nop
        lw      $t0,0($v0)
        lw      $a1,4($v0)
        addiu   $v0,$v0,16
        srl     $t1,$t0,28
        li      $t2,3
        bne     $t1,$t2,hud_chunk
        andi    $t0,$t0,0xffff
        sltu    $t1,$a1,$t9
        bnez    $t1,hud_chunk
        sll     $t0,$t0,4
        lui     $t2,0x3000              # same uncached alias as the UI producer
        or      $a1,$a1,$t2
        addu    $a0,$a1,$t0
        lw      $t1,8($sp)
        sltu    $t1,$t1,$a0
        bnez    $t1,hud_chunk           # texture payloads live outside this arena
        nop
        subu    $t9,$a0,$t2             # consume each generated byte at most once
hud_tag:
        sltu    $t0,$a1,$a0
        beqz    $t0,hud_chunk
        nop
        lw      $t5,menu_start
        subu    $t5,$a1,$t5
        lw      $t6,menu_size
        sltu    $t6,$t5,$t6             # unsigned range also rejects tags before start
        sll     $t5,$t6,4
        sll     $t6,$t6,6
        addu    $t6,$t6,$t5             # native right gutter = 80 pixels
        sw      $t6,24($sp)
        ld      $t0,0($a1)
        ld      $t1,8($a1)
        andi    $a2,$t0,0x7fff          # NLOOP
        dsrl    $t2,$t0,58
        andi    $t2,$t2,3               # FLG
        addiu   $a1,$a1,16
        beqz    $a2,hud_tag
        dsrl    $a3,$t0,60              # NREG (zero encodes sixteen)
        # Ten adjacent full-height sprites implement the tactical screen fade.
        # Preserve their entire width, including the newly visible map edges.
        li      $t5,0x44
        bne     $t1,$t5,hud_test_scene
        li      $t5,10
        bne     $a2,$t5,hud_test_scene
        li      $t5,1
        bne     $t2,$t5,hud_test_scene
        lwu     $t5,0($a1)
        li      $t6,0x79006c00
        bne     $t5,$t6,hud_test_scene
        nop
        lw      $t5,-24($a1)           # preceding REGLIST PRIM/RGBAQ
        sll     $t6,$t5,8
        bnez    $t6,hud_end_fill
        srl     $t5,$t5,24
        li      $t6,128
        subu    $t6,$t6,$t5
        bltzl   $t6,hud_fill_level          # saturate GS alpha above 0x80
        move    $t6,$zero
hud_fill_level:
        sw      $t6,20($sp)
hud_end_fill:
        b       hud_tag
        addiu   $a1,$a1,160
hud_test_scene:
        # UV/ST geometry makes this a visible field. A native black matte
        # submitted BEFORE later scene sprites is a backdrop, not a fade.
        sltiu   $t5,$a3,3
        bnez    $t5,hud_scene_checked
        nop
        andi    $t5,$t1,0xff
        li      $t6,0x31
        beq     $t5,$t6,hud_scene_visible
        li      $t6,0x60
        beq     $t5,$t6,hud_text_visible
        li      $t6,0x10
        beq     $t5,$t6,hud_scene_visible
        li      $t6,0x18
        bne     $t5,$t6,hud_scene_checked
        nop
hud_scene_visible:
        li      $t5,128
        sw      $t5,20($sp)
hud_text_visible:                       # deferred glyphs can follow an opaque wipe
        sw      $a2,16($sp)
hud_scene_checked:
        # SP menus fade with a black sprite; battle animation uses a strip.
        li      $t5,0x441
        beq     $t1,$t5,hud_check_matte
        nop
        li      $t5,0x44441
        bne     $t1,$t5,hud_after_matte
        nop
hud_check_matte:
        bnez    $t2,hud_after_matte
        ld      $t5,0($a1)
        bnez    $t5,hud_after_matte
        lwu     $t5,8($a1)
        bnez    $t5,hud_after_matte
        lhu     $t5,20($a1)
        li      $t6,0x7900
        bne     $t5,$t6,hud_after_matte
        lhu     $t5,16($a1)
        lhu     $t6,32($a1)
        li      $t8,0x6200             # horizontal shutter moving in from left
        beq     $t5,$t8,hud_left_wipe
        li      $t8,0x9e00
        beq     $t5,$t8,hud_right_wipe
        li      $t8,0x6c00
        bne     $t5,$t8,hud_after_matte
        li      $t8,0x9400
        bne     $t6,$t8,hud_after_matte
        li      $t6,10240
        b       hud_wipe_alpha
        lbu     $t5,12($a1)
hud_right_wipe:
        li      $t8,0x9400
        b       hud_wipe_width
        subu    $t6,$t8,$t6
hud_left_wipe:
        addiu   $t6,$t6,-0x6c00
hud_wipe_width:
        blez    $t6,hud_after_matte
        lbu     $t5,12($a1)
        sltiu   $t8,$t6,10240
        bnez    $t8,hud_wipe_alpha
        nop
        li      $t6,10240
hud_wipe_alpha:
        multu   $t5,$t6
        mflo    $t5
        li      $t8,10240
        divu    $zero,$t5,$t8
        mflo    $t5
        li      $t6,128
        subu    $t6,$t6,$t5
        bltzl   $t6,hud_store_matte          # saturate GS alpha above 0x80
        move    $t6,$zero
hud_store_matte:
        sw      $t6,20($sp)
hud_after_matte:
        # Movement, attack and roster previews share this colored world quad.
        # Their corners already use the tactical camera. Applying the UI
        # transform here would move their edges off the corresponding tiles.
        # Projected shadows and unit-attached support labels use STQ/color/XYZF2
        # strips. These share the UI DMA chain but already track the world.
        li      $t5,0x412
        bne     $t1,$t5,hud_color_quad
        dsrl    $t5,$t0,46
        andi    $t5,$t5,0xfff
        li      $t6,0xb9               # PRE + textured world strip (PRIM=92)
        bne     $t5,$t6,hud_format
        li      $t5,3
        bne     $a3,$t5,hud_format
        nop
        bnez    $t2,hud_format
        sll     $t5,$a2,1
        addu    $t5,$t5,$a2
        sll     $t5,$t5,4
        b       hud_tag
        addu    $a1,$a1,$t5
hud_color_quad:
        li      $t5,0x41414141          # RGBAQ/XYZF2 pairs for four corners
        bne     $t1,$t5,hud_format
        dsrl    $t5,$t0,46
        andi    $t5,$t5,0xfff           # PRE plus the native triangle-strip PRIM
        li      $t6,0x99
        bne     $t5,$t6,hud_format
        nop
        bnez    $t2,hud_format
        li      $t6,8
        bne     $a3,$t6,hud_format
        nop
        # Native transition overlay: constant near-black, overscanned quad.
        # Small translucent command highlights use the same register list.
        lwu     $t5,0($a1)
        sltiu   $t5,$t5,2
        beqz    $t5,hud_world_quad
        lhu     $t5,16($a1)
        li      $t6,0x6800
        bne     $t5,$t6,hud_world_quad
        lhu     $t5,48($a1)
        li      $t6,0x9800
        bne     $t5,$t6,hud_world_quad
        lbu     $t5,12($a1)
        li      $t6,128
        subu    $t6,$t6,$t5
        bltzl   $t6,hud_fade_store          # saturate GS alpha above 0x80
        move    $t6,$zero
hud_fade_store:
        sw      $t6,20($sp)
hud_world_quad:
        sll     $t5,$a2,7               # eight packed registers per iteration
        b       hud_tag
        addu    $a1,$a1,$t5
hud_format:
        sltiu   $t3,$t2,2
        beqz    $t3,hud_image
        nop
        bnez    $a3,hud_loop
        li      $t7,16
        li      $a3,16
hud_loop:
        beqz    $t2,hud_registers
        move    $t3,$t1
        li      $t7,8
hud_registers:
        move    $t4,$a3
hud_register:
        sltu    $t5,$a1,$a0
        beqz    $t5,hud_chunk
        andi    $t5,$t3,15
        li      $t6,14
        bne     $t5,$t6,hud_xyz_test
        dsrl    $t3,$t3,4
        bnez    $t2,hud_next
        nop
        lbu     $t5,8($a1)             # packed A+D
        srl     $t6,$t5,1
        li      $t8,32                  # SCISSOR_1 / SCISSOR_2
        bne     $t6,$t8,hud_xyz_test
        nop
        lhu     $t5,0($a1)
        lhu     $t6,2($a1)
        andi    $t5,$t5,0x7ff          # retail packets also set reserved bit 11
        andi    $t6,$t6,0x7ff
        bnez    $t5,hud_clip
        sltiu   $t8,$t6,639
        beqz    $t8,hud_next            # full-screen clip also serves the world
        nop
hud_clip:
        sll     $t8,$t5,1
        addu    $t8,$t8,$t5
        srl     $t8,$t8,2
        addiu   $t8,$t8,80
        lw      $t5,24($sp)
        addu    $t8,$t8,$t5
        sh      $t8,0($a1)
        sll     $t8,$t6,1
        addu    $t8,$t8,$t6
        addiu   $t8,$t8,2               # transform inclusive right boundary
        srl     $t8,$t8,2
        addiu   $t8,$t8,80
        addu    $t8,$t8,$t5
        b       hud_next
        sh      $t8,2($a1)
hud_xyz_test:
        # XYZF2, XYZ2, XYZF3, XYZ3 all store GS X in the low halfword.
        andi    $t6,$t5,0xf6
        li      $t8,4
        bne     $t6,$t8,hud_next
        nop
        lhu     $t5,0($a1)
        ori     $t6,$zero,0x8000
        subu    $t6,$t6,$t5
        addiu   $t6,$t6,2
        sra     $t6,$t6,2
        addu    $t5,$t5,$t6
        lw      $t6,24($sp)
        sll     $t6,$t6,4
        addu    $t5,$t5,$t6
        sh      $t5,0($a1)
hud_next:
        addiu   $t4,$t4,-1
        bnez    $t4,hud_register
        addu    $a1,$a1,$t7
        addiu   $a2,$a2,-1
        bnez    $a2,hud_loop
        nop
        addiu   $a1,$a1,15
        li      $t6,-16
        b       hud_tag
        and     $a1,$a1,$t6
hud_image:
        sll     $a2,$a2,4
        b       hud_tag
        addu    $a1,$a1,$a2
hud_finish:
        lw      $t0,map_drawn
        beqz    $t0,hud_fixed
        ld      $a0,8($sp)
        lui     $t3,%hi(bezel_age)
        sw      $zero,%lo(bezel_age)($t3)
        b       hud_done
        nop
hud_fixed:
        li      $t0,HUD_ARENA+0x30080000-4096
        sltu    $t0,$a0,$t0
        beqz    $t0,hud_done
        lw      $t0,16($sp)
        bnez    $t0,hud_plate
        nop
        sw      $zero,20($sp)
hud_plate:
        lw      $t0,20($sp)
        lw      $t1,bezel_age
        beqz    $t0,hud_age_store
        move    $t2,$zero
        sltiu   $t2,$t1,24
        addu    $t2,$t2,$t1
hud_age_store:
        lui     $t3,%hi(bezel_age)
        sw      $t2,%lo(bezel_age)($t3)
        addiu   $t2,$t2,-8              # skip fleeting load/transition fields
        bgez    $t2,hud_ramp
        nop
        move    $t2,$zero
hud_ramp:
        sll     $t2,$t2,3
        sltu    $t1,$t2,$t0
        beqz    $t1,hud_plate_draw
        nop
        sw      $t2,20($sp)
hud_plate_draw:
        jal     bezel_append
        move    $v0,$zero
        jal     HUD_SUBMIT
        nop
hud_done:
        lui     $t0,%hi(menu_size)
        sw      $zero,%lo(menu_size)($t0)
        ld      $ra,0($sp)
        ld      $a0,8($sp)
        jr      $ra
        addiu   $sp,$sp,32
